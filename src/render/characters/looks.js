/**
 * render/characters/looks.js — внешность героев в аниме-стиле (только данные).
 *
 * Причёска задаётся в локальной системе головы (единица — радиус черепа):
 *   x — вправо (ракеточная сторона), y — вверх, z — вперёд (лицо).
 *   caps   — масса волос на черепе: всё, что выше линии роста волос. Линия задана широтой
 *            (рад, 0 — «экватор» на уровне глаз) спереди f, сбоку s и сзади b.
 *            buzz — коротко выбритая зона (тон кожи), mohawk-полоса — высокие s.
 *   fringe — чёлка: n прядей вдоль линии лба (len — длина, spread — ширина по азимуту,
 *            sweep — косой зачёс, w — полуширина, blunt — ровный срез).
 *   locks  — отдельные пряди: r — корень на сфере, d — направление к кончику, l — длина,
 *            w — полуширина у корня, b — изгиб, s — раскачивание (вторичная динамика), blunt.
 *   tail   — хвост (цепочка), band — повязка с лентами, clip — заколка, beard — бородка.
 * Все герои оригинальные; цвета формы — из config (p.color / p.accent).
 */

/** Зеркальная копия прядей по оси x (симметричные причёски). */
function mir(list) {
  const out = [];
  for (const L of list) {
    out.push(L);
    if (L.m) out.push({ ...L, r: [-L.r[0], L.r[1], L.r[2]], d: [-L.d[0], L.d[1], L.d[2]], b: -(L.b || 0), m: false });
  }
  return out;
}

